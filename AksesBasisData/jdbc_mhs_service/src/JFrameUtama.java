    private void tampilkanData() {

    dlm.clear();
    dlmId.clear();

    for(Mahasiswa m : service.getAll()) {

        dlmId.addElement(
            String.valueOf(m.getId())
        );

        dlm.addElement(
            m.getNama()
        );

    }
    System.out.println(
    "Jumlah ID = " + dlmId.size()
    );

    System.out.println(
    "Jumlah Nama = " + dlm.size()
    );
}

    private void addItem(String namaItem){
    dlm.addElement(namaItem);
    }
    
  
