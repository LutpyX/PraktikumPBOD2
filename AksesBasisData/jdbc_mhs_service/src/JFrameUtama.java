    private void jButtonTambahkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahkanActionPerformed
        // TODO add your handling code here:
    String nama =
            jTextFieldNamaTambah.getText().trim();

    if(nama.isEmpty()) {

        jLabelReset.setText(
                "Nama tidak boleh kosong"
        );

        return;
    }

    service.add(
            new Mahasiswa(
                    0,
                    nama
            )
    );

    tampilkanData();

    jTextFieldNamaTambah.setText("");

    jLabelReset.setText(
            "Data berhasil ditambahkan"
    );

    }//GEN-LAST:event_jButtonTambahkanActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        
        if(jTextFieldIdEdit.getText().trim().isEmpty()
        || jTextFieldNamaEdit.getText().trim().isEmpty()) {

    jLabelReset.setText(
            "Data edit belum lengkap"
    );

    return;
}
        int id = Integer.parseInt(
            jTextFieldIdEdit.getText()
        );

    String nama =
            jTextFieldNamaEdit.getText();

    service.update(
            new Mahasiswa(
                    id,
                    nama
            )
    );

    tampilkanData();

    jTextFieldIdEdit.setText("");
    jTextFieldNamaEdit.setText("");

    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        // TODO add your handling code here:
        if(jTextFieldIdHapus.getText().trim().isEmpty()) {

    jLabelReset.setText(
            "Pilih data yang akan dihapus"
    );

    return;
}
        int id = Integer.parseInt(
            jTextFieldIdHapus.getText()
    );

    service.delete(id);

    tampilkanData();

    jTextFieldIdHapus.setText("");
    jTextFieldNamaHapus.setText("");
    }//GEN-LAST:event_jButtonHapusActionPerformed

    private void jButtonResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonResetActionPerformed
        // TODO add your handling code here:
         if(service.isEmpty()) {

        jLabelReset.setText(
            "Tidak ada data untuk direset"
        );

        return;
    }

    service.indexReset();

    tampilkanData();

    jLabelReset.setText(
        "Index berhasil direset"
    );

    }//GEN-LAST:event_jButtonResetActionPerformed

    private void jListMahasiswaValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jListMahasiswaValueChanged
        // TODO add your handling code here:
         int index =
            jListMahasiswa.getSelectedIndex();

    if(index == -1)
        return;

    String id =
            jListId.getModel()
                   .getElementAt(index);

    String nama =
            jListMahasiswa.getModel()
                          .getElementAt(index);

    jTextFieldIdEdit.setText(id);
    jTextFieldNamaEdit.setText(nama);

    jTextFieldIdHapus.setText(id);
    jTextFieldNamaHapus.setText(nama);
    }//GEN-LAST:event_jListMahasiswaValueChanged

